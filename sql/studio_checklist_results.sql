-- Studio Checklist Results — per-review snapshot of the Kapruka brand
-- guidelines checklist for a studio_calendar slot. Run once in Supabase →
-- SQL Editor. Idempotent.
--
-- Both the Head of Studio review (slot detail modal) and the Digital
-- Marketing review (DM Approvals tab) save a row here each time they tick
-- through the checklist. Append-only, like studio_activity_log — every save
-- is a new row so history is never lost; the app always reads back the most
-- recent row per (slot_id, stage).
--
-- `stage` is 'head' or 'dm'. `slot_id` is studio_calendar.id — the same id
-- is used for both stages so a post's Head and DM checklist history line up.
-- `results` is a JSON array of {key, label, passed}.

create table if not exists studio_checklist_results (
  id            bigint generated by default as identity primary key,
  slot_id       bigint not null,          -- studio_calendar.id
  stage         text   not null,          -- 'head' | 'dm'
  results       jsonb  not null,          -- [{key, label, passed}, ...]
  passed_count  int    not null,
  failed_count  int    not null,
  reviewer      text,
  created_at    timestamptz not null default now()
);

create index if not exists idx_studio_checklist_slot
  on studio_checklist_results (slot_id, stage, created_at);

-- The app talks to Supabase with the anon key, so allow anon/authenticated to
-- read and insert (append-only — no update/delete granted).
alter table studio_checklist_results enable row level security;

drop policy if exists studio_checklist_results_read on studio_checklist_results;
create policy studio_checklist_results_read
  on studio_checklist_results for select using (true);

drop policy if exists studio_checklist_results_insert on studio_checklist_results;
create policy studio_checklist_results_insert
  on studio_checklist_results for insert with check (true);

grant select, insert on studio_checklist_results to anon, authenticated;
grant usage, select on sequence studio_checklist_results_id_seq to anon, authenticated;
